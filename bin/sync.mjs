#!/usr/bin/env node
// tanner-agent-standards — sync shared, agent-agnostic conventions into a repo.
//
// Zero dependencies (Node built-ins only). It writes AGENTS.md — the open, tool-neutral
// standard read by Claude Code, Cursor, Codex, Copilot, Gemini, etc. — as real text, so
// every agent sees the same rules. The shared rules live between markers; everything else
// in the file (your app description, project-specific rules) is never touched.
//
// Usage, run from a consumer repo root:
//   npx tanner-agent-standards sync     inject/refresh the managed block + skills (idempotent)
//   npx tanner-agent-standards update   npm update this package, then sync (one step)
//   npx tanner-agent-standards init     same as sync, with brand-new-repo onboarding output
//   npx tanner-agent-standards check    exit non-zero if the repo is out of date (CI / pre-push)

import {
  readFileSync,
  writeFileSync,
  existsSync,
  cpSync,
  mkdirSync,
  readdirSync,
  rmSync,
} from "node:fs";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import { dirname, isAbsolute, join, posix, resolve, win32 } from "node:path";

const PKG_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const TARGET = process.cwd();

const BEGIN = "<!-- BEGIN:tanner-agent-standards -->";
const END = "<!-- END:tanner-agent-standards -->";
const EVE_MARKER = "<!-- Generated by tanner-agent-standards. Do not edit directly. -->";

const read = (p) => readFileSync(p, "utf8");
const VERSION = JSON.parse(read(join(PKG_ROOT, "package.json"))).version;

// Rewrite `[[skill-name]]` cross-references into a followable pointer for one agent's tree.
// The wikilink syntax reads well in source but resolves to nothing outside a wiki — Claude
// Code loads a linked skill by description match, and Cursor / Codex / Gemini just see literal
// brackets. `pathFor(name)` returns the target-native relative path for a skill slug, so each
// agent gets `` `name` (`the/real/path`) `` — a real file it can open.
function resolveWikilinks(text, pathFor) {
  return text.replace(/\[\[([a-z0-9-]+)\]\]/g, (_, name) => `\`${name}\` (\`${pathFor(name)}\`)`);
}

const claudePath = (name) => `.claude/skills/${name}/SKILL.md`;
const cursorPath = (name) => `.cursor/rules/${name}.mdc`;

// Split a SKILL.md into its YAML frontmatter fields and its markdown body.
function parseSkill(raw) {
  const m = raw.match(/^---\n([\s\S]*?)\n---\n?([\s\S]*)$/);
  if (!m) return { description: "", frontmatter: "", body: raw.trim() };
  const fm = m[1];
  const field = (k) => (fm.match(new RegExp(`^${k}:\\s*(.+)$`, "m")) || [])[1]?.trim() || "";
  return { description: field("description"), frontmatter: `---\n${fm}\n---`, body: m[2].trim() };
}

// Every skill in the package, keyed by its directory name (the canonical slug).
function skillsList() {
  const src = join(PKG_ROOT, "skills");
  if (!existsSync(src)) return [];
  return readdirSync(src, { withFileTypes: true })
    .filter((d) => d.isDirectory())
    .map((d) => d.name)
    .sort()
    .map((name) => {
      const file = join(src, name, "SKILL.md");
      if (!existsSync(file)) return null;
      const { description, frontmatter, body } = parseSkill(read(file));
      return { name, description, frontmatter, body };
    })
    .filter(Boolean);
}

// A discoverable index of the synced skills, injected into AGENTS.md so agents that
// have no native skills folder — OpenAI Codex, Copilot, Gemini — still find them by
// reading the one file they all read. Generated from the skills' own frontmatter, so
// `check` stays deterministic.
function skillsSection(skills) {
  if (!skills.length) return "";
  const items = skills.map(
    (s) =>
      `- **${s.name}** — ${s.description}\n` +
      `  Read: \`.claude/skills/${s.name}/SKILL.md\` · Cursor: \`.cursor/rules/${s.name}.mdc\``,
  );
  return [
    "## Skills",
    "",
    "Deep-dive references synced into this repo. Claude Code auto-loads them from",
    "`.claude/skills/`; Cursor auto-attaches them from `.cursor/rules/`; Codex and other",
    "AGENTS.md-based agents should open the referenced file when a task matches its description.",
    "",
    ...items,
  ].join("\n");
}

function managedBlock() {
  const base = read(join(PKG_ROOT, "AGENTS.base.md")).trim();
  const stamp = `<!-- v${VERSION} · managed block — do not edit here; run \`npx tanner-agent-standards sync\` -->`;
  const skills = skillsSection(skillsList());
  const body = skills ? `${base}\n\n${skills}` : base;
  return `${BEGIN}\n${stamp}\n\n${body}\n${END}`;
}

const escapeRe = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
const blockRe = () =>
  new RegExp(`${escapeRe(BEGIN)}[\\s\\S]*?${escapeRe(END)}`);

// Replace the managed block if markers exist; otherwise insert it after the first H1
// (or prepend if there is no H1), leaving all other content untouched.
function inject(content, block) {
  if (blockRe().test(content)) return content.replace(blockRe(), block);
  const lines = content.split("\n");
  const h1 = lines.findIndex((l) => /^#\s/.test(l));
  if (h1 === -1) return `${block}\n\n${content}`;
  let i = h1 + 1;
  while (i < lines.length && lines[i].trim() === "") i++; // skip blank lines after the H1
  if (i < lines.length && !/^#{1,6}\s/.test(lines[i])) {  // an intro paragraph (not a heading)?
    while (i < lines.length && lines[i].trim() !== "") i++; // keep it above the block
  }
  lines.splice(i, 0, "", block);
  return lines.join("\n");
}

function ensureAgents() {
  const p = join(TARGET, "AGENTS.md");
  const before = existsSync(p) ? read(p) : read(join(PKG_ROOT, "templates", "AGENTS.md"));
  const created = !existsSync(p);
  let next = inject(before, managedBlock());
  if (!next.endsWith("\n")) next += "\n";
  writeFileSync(p, next);
  return { created, changed: created || next !== before };
}

function ensureClaude() {
  const p = join(TARGET, "CLAUDE.md");
  if (existsSync(p)) return { created: false };
  writeFileSync(p, "See @AGENTS.md\n"); // Claude reads AGENTS.md; other agents already do
  return { created: true };
}

// Fan every skill out to each agent's native home. The content is identical markdown;
// each adapter reshapes only the wrapper to that tool's convention.
//  • Claude Code — .claude/skills/<name>/SKILL.md, copied verbatim (preserves any
//    supporting files in the skill dir); auto-discovered as a native skill.
//  • Cursor — .cursor/rules/<name>.mdc: frontmatter (description) + body, written as an
//    "agent-requested" rule Cursor pulls in when the description matches the task.
//  • OpenAI Codex / Copilot / Gemini — no skills dir; they read the `## Skills` index
//    that managedBlock() injects into AGENTS.md, which points them at the files above.
function syncSkills() {
  const skills = skillsList();
  if (!skills.length) return [];

  // Claude: tree copy (preserves any supporting files in a skill dir), then rewrite each
  // SKILL.md's wikilinks to Claude-native paths so a linked skill is one open away.
  const claudeDst = join(TARGET, ".claude", "skills");
  mkdirSync(claudeDst, { recursive: true });
  cpSync(join(PKG_ROOT, "skills"), claudeDst, { recursive: true });
  for (const s of skills) {
    const f = join(claudeDst, s.name, "SKILL.md");
    writeFileSync(f, resolveWikilinks(read(f), claudePath));
  }

  // Cursor: one .mdc rule per skill, wikilinks resolved to the sibling .mdc rules.
  const cursorDst = join(TARGET, ".cursor", "rules");
  mkdirSync(cursorDst, { recursive: true });
  for (const s of skills) {
    const body = resolveWikilinks(s.body, cursorPath);
    const mdc = `---\ndescription: ${s.description}\nalwaysApply: false\n---\n\n${body}\n`;
    writeFileSync(join(cursorDst, `${s.name}.mdc`), mdc);
  }

  return skills.map((s) => s.name);
}

const skillTitle = (name) =>
  name
    .split("-")
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join(" ");

function eveConfig() {
  const packageFile = join(TARGET, "package.json");
  if (!existsSync(packageFile)) return null;
  const config = JSON.parse(read(packageFile)).tannerAgentStandards?.eve;
  if (config === undefined) return null;
  if (!config || typeof config !== "object" || Array.isArray(config)) {
    throw new Error("Invalid tannerAgentStandards.eve configuration: expected an object.");
  }

  const directory = config.directory;
  const invalidDirectory =
    typeof directory !== "string" ||
    !directory.trim() ||
    directory.includes("\0") ||
    isAbsolute(directory) ||
    win32.isAbsolute(directory) ||
    directory.replaceAll("\\", "/").split("/").includes("..");
  if (invalidDirectory) {
    throw new Error(
      'Invalid tannerAgentStandards.eve.directory: use a repository-relative path without ".." traversal.',
    );
  }

  const normalizedDirectory = posix.normalize(directory.replaceAll("\\", "/"));
  const skills = config.skills;
  if (!skills || typeof skills !== "object" || Array.isArray(skills)) {
    throw new Error("Invalid tannerAgentStandards.eve.skills: expected an object keyed by skill name.");
  }

  const available = new Map(skillsList().map((skill) => [skill.name, skill]));
  const requested = Object.keys(skills).sort().map((name) => {
    if (!available.has(name)) {
      throw new Error(
        `Unknown Eve skill "${name}". Available skills: ${[...available.keys()].join(", ")}.`,
      );
    }
    const settings = skills[name];
    if (!settings || typeof settings !== "object" || Array.isArray(settings)) {
      throw new Error(`Invalid Eve configuration for "${name}": expected an object.`);
    }
    const bundle = settings.bundle ?? [];
    if (!Array.isArray(bundle) || bundle.some((dependency) => typeof dependency !== "string")) {
      throw new Error(`Invalid Eve bundle for "${name}": expected an array of skill names.`);
    }
    const seen = new Set();
    for (const dependency of bundle) {
      if (!available.has(dependency)) {
        throw new Error(`Unknown bundled Eve skill "${dependency}" requested by "${name}".`);
      }
      if (dependency === name) {
        throw new Error(`Eve skill "${name}" cannot bundle itself.`);
      }
      if (seen.has(dependency)) {
        throw new Error(`Eve skill "${name}" bundles "${dependency}" more than once.`);
      }
      seen.add(dependency);
    }
    return { name, bundle, skill: available.get(name) };
  });

  return { directory: normalizedDirectory, requested, available };
}

function rewriteEveWikilinks(text, localAnchors) {
  return text.replace(/\[\[([a-z0-9-]+)\]\]/g, (_, name) => {
    const title = skillTitle(name);
    const anchor = localAnchors.get(name);
    return anchor ? `[${title}](#${anchor})` : title;
  });
}

function renderEveSkill(request, available) {
  const localAnchors = new Map([[request.name, request.name]]);
  for (const dependency of request.bundle) {
    localAnchors.set(dependency, `bundled-reference-${dependency}`);
  }
  const sections = [
    request.skill.frontmatter,
    EVE_MARKER,
    rewriteEveWikilinks(request.skill.body, localAnchors),
  ];
  for (const dependency of request.bundle) {
    const skill = available.get(dependency);
    sections.push(
      `## Bundled Reference: ${skillTitle(dependency)}`,
      rewriteEveWikilinks(skill.body, localAnchors),
    );
  }
  return `${sections.join("\n\n").trim()}\n`;
}

function eveOutputs(config) {
  if (!config) return [];
  return config.requested.map((request) => ({
    name: request.name,
    relativePath: posix.join(config.directory, request.name, "SKILL.md"),
    content: renderEveSkill(request, config.available),
  }));
}

function staleEveOutputs(config, expectedNames) {
  if (!config) return [];
  const root = join(TARGET, config.directory);
  if (!existsSync(root)) return [];
  return readdirSync(root, { withFileTypes: true })
    .filter((entry) => entry.isDirectory() && !expectedNames.has(entry.name))
    .map((entry) => join(root, entry.name, "SKILL.md"))
    .filter((file) => existsSync(file) && read(file).includes(EVE_MARKER));
}

function syncEve(config) {
  if (!config) return null;
  const outputs = eveOutputs(config);
  const expectedNames = new Set(outputs.map((output) => output.name));
  for (const file of staleEveOutputs(config, expectedNames)) {
    rmSync(file);
    const parent = dirname(file);
    if (readdirSync(parent).length === 0) rmSync(parent, { recursive: true });
  }
  for (const output of outputs) {
    const file = join(TARGET, output.relativePath);
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, output.content);
  }
  return outputs.map((output) => posix.dirname(output.relativePath));
}

function checkEve(fail, config) {
  if (!config) return;
  const outputs = eveOutputs(config);
  for (const output of outputs) {
    const file = join(TARGET, output.relativePath);
    if (!existsSync(file)) {
      fail(`Eve skill missing at ${output.relativePath} — run \`npx tanner-agent-standards sync\`.`);
    }
    if (read(file) !== output.content) {
      fail(`Eve skill drift at ${output.relativePath} — run \`npx tanner-agent-standards sync\`.`);
    }
  }
  const stale = staleEveOutputs(config, new Set(outputs.map((output) => output.name)));
  if (stale.length) {
    const relative = posix.relative(TARGET.replaceAll("\\", "/"), stale[0].replaceAll("\\", "/"));
    fail(`Stale generated Eve skill at ${relative} — run \`npx tanner-agent-standards sync\`.`);
  }
}

// The current hook filename, and the one it superseded. `sync` migrates any consumer still on
// the old pre-commit gate over to the pre-push one (see wireCleanupHook).
const HOOK_FILE = "pre-push-cleanup.mjs";
const OLD_HOOK_FILE = "pre-commit-cleanup.mjs";

// The command string that identifies our managed PreToolUse entry in a consumer's
// settings.json — used to keep the wiring idempotent across re-syncs.
const cleanupHookCommand = `node "$CLAUDE_PROJECT_DIR/.claude/hooks/${HOOK_FILE}"`;

// Fan the shared hooks out to the consumer. Unlike skills, hooks are Claude Code-specific:
// they land in .claude/hooks/ and get registered in .claude/settings.json. Every other agent
// still gets the paired skill through the AGENTS.md index — the hook only adds Claude's
// automatic trigger on top. (The maintainer-only changelog hook lives directly under this
// package's .claude/ and is never in `hooks/`, so it is never distributed.)
function syncHooks() {
  const src = join(PKG_ROOT, "hooks");
  if (!existsSync(src)) return [];
  const files = readdirSync(src).filter((f) => f.endsWith(".mjs"));
  if (!files.length) return [];

  const dst = join(TARGET, ".claude", "hooks");
  mkdirSync(dst, { recursive: true });
  cpSync(src, dst, { recursive: true }); // additive — leaves any repo-local hooks in place

  const stale = join(dst, OLD_HOOK_FILE); // the renamed pre-commit gate, if this repo had it
  if (existsSync(stale)) rmSync(stale);

  wireCleanupHook();
  return files;
}

// Register the pre-push cleanup hook in the consumer's .claude/settings.json without disturbing
// anything else they have there. Additive and idempotent: identified by its command string, so a
// re-sync never duplicates it. Also migrates a consumer off the old pre-commit gate — any
// PreToolUse entry pointing at the superseded hook file is dropped before the new one is added, so
// a re-sync moves them over cleanly instead of leaving both firing. If the file exists but isn't
// valid JSON we leave it alone and print a note rather than risk corrupting the user's settings.
function wireCleanupHook() {
  const p = join(TARGET, ".claude", "settings.json");
  let settings = {};
  if (existsSync(p)) {
    try {
      settings = JSON.parse(read(p));
    } catch {
      console.warn(
        `  ! .claude/settings.json isn't valid JSON — skipped hook wiring. Add the PreToolUse\n` +
          `    entry for ${HOOK_FILE} by hand, or fix the JSON and re-run sync.`,
      );
      return;
    }
  }
  settings.hooks ||= {};
  settings.hooks.PreToolUse ||= [];

  const list = settings.hooks.PreToolUse;
  const before = JSON.stringify(list);
  // Drop the superseded pre-commit registration if the consumer still has it.
  settings.hooks.PreToolUse = list.filter(
    (entry) => !JSON.stringify(entry).includes(OLD_HOOK_FILE),
  );
  const wired = JSON.stringify(settings.hooks.PreToolUse).includes(HOOK_FILE);

  if (!wired) {
    settings.hooks.PreToolUse.push({
      matcher: "Bash",
      hooks: [
        {
          type: "command",
          command: cleanupHookCommand,
          statusMessage: "Checking changes are clean before push…",
        },
      ],
    });
  } else if (JSON.stringify(settings.hooks.PreToolUse) === before) {
    return; // already on the pre-push gate and nothing stale to remove — no write needed
  }
  writeFileSync(p, `${JSON.stringify(settings, null, 2)}\n`);
}

function check() {
  const p = join(TARGET, "AGENTS.md");
  const fail = (msg) => {
    console.error(`✗ ${msg}`);
    process.exit(1);
  };
  if (!existsSync(p)) fail("AGENTS.md missing — run `npx tanner-agent-standards sync`");
  const m = read(p).match(blockRe());
  if (!m) fail("managed block missing — run `npx tanner-agent-standards sync`");
  if (m[0].trim() !== managedBlock().trim())
    fail(`tanner-agent-standards drift — AGENTS.md is behind v${VERSION}. Run \`npx tanner-agent-standards sync\`.`);
  checkEve(fail, eveConfig());
  console.log(`✓ tanner-agent-standards v${VERSION} in sync`);
}

// npm update this package in the consumer, then run sync from the freshly-installed
// version. Re-execs so `sync` runs the just-pulled code, not this (now-stale) process.
function update() {
  const pkg = "tanner-agent-standards";
  console.log(`Updating ${pkg} in ${TARGET}…`);
  const up = spawnSync("npm", ["update", pkg], { stdio: "inherit", cwd: TARGET });
  if (up.status !== 0) {
    console.error("✗ npm update failed — skipping sync. Fix the install and retry.");
    process.exit(up.status || 1);
  }
  const sync = spawnSync("npx", ["--no-install", pkg, "sync"], {
    stdio: "inherit",
    cwd: TARGET,
  });
  process.exit(sync.status ?? 0);
}

const cmd = process.argv[2] || "sync";

if (cmd === "--version" || cmd === "-v") {
  console.log(VERSION);
} else if (cmd === "check") {
  try {
    check();
  } catch (error) {
    console.error(`✗ ${error.message}`);
    process.exit(1);
  }
} else if (cmd === "update") {
  update();
} else if (cmd === "sync" || cmd === "init") {
  try {
    const config = eveConfig();
    const a = ensureAgents();
    const c = ensureClaude();
    const skills = syncSkills();
    const eve = syncEve(config);
    const hooks = syncHooks();
    console.log(`tanner-agent-standards v${VERSION} → ${TARGET}`);
    console.log(`  • AGENTS.md  ${a.created ? "created" : a.changed ? "updated" : "already current"}`);
    console.log(`  • CLAUDE.md  ${c.created ? "created" : "kept"}`);
    if (eve) {
      console.log(`  • Claude  ${skills.length ? "→ .claude/skills" : "none"}`);
      console.log(`  • Cursor  ${skills.length ? "→ .cursor/rules" : "none"}`);
      console.log(`  • Eve     ${eve.length ? `→ ${eve.join(", ")}` : "none configured"}`);
    } else {
      console.log(
        `  • skills     ${skills.length ? `${skills.join(", ")} → .claude/skills, .cursor/rules` : "none"}`,
      );
    }
    console.log(`  • hooks      ${hooks.length ? `${hooks.join(", ")} → .claude/hooks, .claude/settings.json` : "none"}`);
    if (a.created || cmd === "init") {
      console.log("\nNext: replace the app-description comment near the top of AGENTS.md, then commit.");
    }
  } catch (error) {
    console.error(`✗ ${error.message}`);
    process.exit(1);
  }
} else {
  console.log("Usage: tanner-agent-standards <sync|update|init|check>");
  process.exit(1);
}
